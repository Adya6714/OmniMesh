let leafletLoadPromise = null;

function loadLeafletHeatPlugin() {
  return new Promise((resolve, reject) => {
    if (typeof window === "undefined") return resolve();
    if (window.L?.heatLayer) return resolve();
    const script = document.createElement("script");
    script.src = "https://unpkg.com/leaflet.heat@0.2.0/dist/leaflet-heat.js";
    script.async = true;
    script.onload = () => resolve();
    script.onerror = () => reject(new Error("leaflet.heat failed to load"));
    document.head.appendChild(script);
  });
}

function loadLeafletAssets() {
  if (typeof window === "undefined") return Promise.resolve();
  if (window.L?.heatLayer) return Promise.resolve();
  if (leafletLoadPromise) return leafletLoadPromise;

  leafletLoadPromise = new Promise((resolve, reject) => {
    const finish = () => loadLeafletHeatPlugin().then(resolve).catch(reject);

    if (window.L) {
      finish();
      return;
    }

    const css = document.createElement("link");
    css.rel = "stylesheet";
    css.href = "https://unpkg.com/leaflet@1.9.4/dist/leaflet.css";
    document.head.appendChild(css);

    const script = document.createElement("script");
    script.src = "https://unpkg.com/leaflet@1.9.4/dist/leaflet.js";
    script.async = true;
    script.onload = () => finish();
    script.onerror = () => reject(new Error("Leaflet failed to load"));
    document.head.appendChild(script);
  });

  return leafletLoadPromise;
}

