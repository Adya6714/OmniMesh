function FieldMapInfoBody({ packet }) {
  const lat = packet.lat;
  const lng = packet.lng ?? packet.lon;
  const mapsUrl =
    lat != null && lng != null
      ? `https://www.google.com/maps?q=${lat},${lng}&z=17`
      : null;
  const u = (packet.urgency || "GREEN").toLowerCase();

  return (
    <div className={`field-map-infowindow-inner field-map-infowindow--${u}`}>
      <div className={`field-map-infowindow-urgency field-map-iw-${u}`}>
        {packet.urgency} · {priorityHeading(packet).replace(/:$/, "")}
      </div>
      <div className="field-map-infowindow-id">{formatResponderPacketId(packet)}</div>
      <p className="field-map-infowindow-injury">{packet.injury || "Unknown"}</p>
      <dl className="field-map-infowindow-dl">
        <div>
          <dt>Location</dt>
          <dd>
            {lat != null && lng != null ? (
              <>
                {lat.toFixed(5)}°, {lng.toFixed(5)}°
                {mapsUrl ? (
                  <>
                    {" · "}
                    <a href={mapsUrl} target="_blank" rel="noopener noreferrer">
                      Open in Maps
                    </a>
                  </>
                ) : null}
              </>
            ) : (
              "—"
            )}
          </dd>
        </div>
        <div>
          <dt>Signals</dt>
          <dd>{signalsLine(packet)}</dd>
        </div>
        <div>
          <dt>Source</dt>
          <dd>{sourceLine(packet)}</dd>
        </div>
      </dl>
    </div>
  );
}

const HEAT_LAYER_OPTS = {
  radius: 35,
  blur: 25,
  maxZoom: 17,
  gradient: { 0.4: "#FBBC04", 0.65: "#EA4335", 1: "#A50E0E" },
};

function runSonarSweep(map) {
  const L = typeof window !== "undefined" ? window.L : null;
  if (!map || !L) return;
  const center = map.getCenter();
  const circle = L.circle(center, {
    radius: 50,
    color: "#34A853",
    weight: 2,
    fillOpacity: 0,
    opacity: 0.6,
  }).addTo(map);

  const durationMs = 3000;
  const start = typeof performance !== "undefined" ? performance.now() : Date.now();

  function frame(now) {
    const t = Math.min(1, (now - start) / durationMs);
    const radius = 50 + (500 - 50) * t;
    const opacity = 0.6 * (1 - t);
    circle.setRadius(radius);
    circle.setStyle({ opacity, fillOpacity: 0 });
    if (t < 1) {
      requestAnimationFrame(frame);
    } else {
      map.removeLayer(circle);
    }
  }
  requestAnimationFrame(frame);
}

function LeafletFieldMap({ packets, selectedId, setSelectedId }) {
  const mapElRef = useRef(null);
  const mapRef = useRef(null);
  const markersByIdRef = useRef({});
  const resizeHandlerRef = useRef(null);
  const heatLayerRef = useRef(null);
  const sonarIntervalRef = useRef(null);
  const [mapReady, setMapReady] = useState(false);

  useEffect(() => {
    let cancelled = false;

    (async () => {
      try {
        await loadLeafletAssets();
      } catch {
        return;
      }
      if (cancelled || !mapElRef.current || mapRef.current) return;

      const L = window.L;
      const first = packets.find((p) => p.lat != null && (p.lng != null || p.lon != null));
      const center = first ? [first.lat, first.lng ?? first.lon] : [FALLBACK_CENTER.lat, FALLBACK_CENTER.lng];

      const map = L.map(mapElRef.current, { zoomControl: false }).setView(center, 14);

      L.tileLayer("https://{s}.basemaps.cartocdn.com/rastertiles/voyager/{z}/{x}/{y}{r}.png", {
        attribution: "© OpenStreetMap © CARTO",
        subdomains: "abcd",
        maxZoom: 20,
      }).addTo(map);

      L.control.zoom({ position: "bottomright" }).addTo(map);

      mapRef.current = map;

      map.once("load", () => {
        if (cancelled || mapRef.current !== map) return;
        runSonarSweep(map);
        sonarIntervalRef.current = window.setInterval(() => {
          runSonarSweep(mapRef.current);
        }, 4000);
      });

      setMapReady(true);

      resizeHandlerRef.current = () => map.invalidateSize();
      window.addEventListener("resize", resizeHandlerRef.current);
    })();

    return () => {
      cancelled = true;
      setMapReady(false);
      if (sonarIntervalRef.current != null) {
        window.clearInterval(sonarIntervalRef.current);
        sonarIntervalRef.current = null;
      }
      heatLayerRef.current = null;
      if (resizeHandlerRef.current) {
        window.removeEventListener("resize", resizeHandlerRef.current);
        resizeHandlerRef.current = null;
      }
      if (mapRef.current) {
        mapRef.current.remove();
        mapRef.current = null;
      }
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useEffect(() => {
    const map = mapRef.current;
    const el = mapElRef.current;
    if (!mapReady || !map || !el || typeof ResizeObserver === "undefined") return undefined;
    const ro = new ResizeObserver(() => {
      map.invalidateSize({ animate: false });
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, [mapReady]);

  useEffect(() => {
    const map = mapRef.current;
    const L = typeof window !== "undefined" ? window.L : null;
    if (!mapReady || !map || !L) return undefined;

    Object.values(markersByIdRef.current).forEach((m) => {
      try {
        m.remove();
      } catch {
        /* ignore */
      }
    });
    markersByIdRef.current = {};

    packets.forEach((pkt) => {
      const lat = pkt.lat;
      const lng = pkt.lng ?? pkt.lon;
      if (lat == null || lng == null) return;

      const selected = pkt.id === selectedId;
      const marker = L.marker([lat, lng], {
        icon: leafletPinIcon(L, pkt.urgency, selected),
      }).addTo(map);

      marker.bindPopup(leafletPopupHtml(pkt), {
        maxWidth: 320,
        className: "dark-popup",
      });

      marker.on("click", () => {
        setSelectedId(pkt.id);
      });

      markersByIdRef.current[pkt.id] = marker;

      requestAnimationFrame(() => {
        const iconEl =
          typeof marker.getElement === "function" ? marker.getElement() : marker._icon;
        if (iconEl && pkt.urgency === "RED") iconEl.classList.add("pulsing-marker");
      });
    });

    if (typeof L.heatLayer === "function") {
      if (!heatLayerRef.current) {
        heatLayerRef.current = L.heatLayer([], HEAT_LAYER_OPTS).addTo(map);
      }
      const redHeat = packets
        .filter((p) => p.urgency === "RED" && p.lat != null && (p.lng ?? p.lon) != null)
        .map((p) => [p.lat, p.lng ?? p.lon, 1.0]);
      heatLayerRef.current.setLatLngs(redHeat);
    }

    const sel = packets.find((p) => p.id === selectedId);
    if (sel && sel.lat != null && (sel.lng ?? sel.lon) != null) {
      map.setView([sel.lat, sel.lng ?? sel.lon], Math.max(map.getZoom(), 16), { animate: true });
      const mk = markersByIdRef.current[sel.id];
      if (mk) mk.openPopup();
    } else if (packets.length > 0) {
      const valid = packets.filter((p) => p.lat != null && (p.lng ?? p.lon) != null);
      if (valid.length > 0) {
        const b = L.latLngBounds(valid.map((p) => [p.lat, p.lng ?? p.lon]));
        map.fitBounds(b.pad(0.15));
      }
    }

    map.invalidateSize();

    return undefined;
  }, [packets, selectedId, setSelectedId, mapReady]);

  return (
    <div className="field-map-stack field-map-tiles-voyager">
      <div ref={mapElRef} className="responder-map-leaflet" />
    </div>
  );
}

function GoogleFieldMap({ packets, selectedId, setSelectedId }) {
  const apiKey = resolveGoogleMapsApiKey();
  const { isLoaded, loadError } = useJsApiLoader({
    googleMapsApiKey: apiKey,
    libraries: GOOGLE_MAP_LIBS,
  });

  const mapRef = useRef(null);
  const validPackets = useMemo(
    () => packets.filter((p) => p.lat != null && (p.lng != null || p.lon != null)),
    [packets],
  );

  const center = useMemo(() => {
    if (validPackets.length === 0) return FALLBACK_CENTER;
    const lat = validPackets.reduce((s, p) => s + p.lat, 0) / validPackets.length;
    const lng = validPackets.reduce((s, p) => s + (p.lng ?? p.lon), 0) / validPackets.length;
    return { lat, lng };
  }, [validPackets]);

  const selectedPacket = useMemo(
    () => packets.find((p) => p.id === selectedId && p.lat != null && (p.lng ?? p.lon) != null),
    [packets, selectedId],
  );

  const onLoad = useCallback((map) => {
    mapRef.current = map;
  }, []);

  const onUnmount = useCallback(() => {
    mapRef.current = null;
  }, []);

  useEffect(() => {
    const map = mapRef.current;
    if (!map || !isLoaded || !window.google?.maps) return;

    if (selectedPacket) {
      const lng = selectedPacket.lng ?? selectedPacket.lon;
      map.panTo({ lat: selectedPacket.lat, lng });
      map.setZoom(Math.max(map.getZoom() || 14, 16));
      return;
    }

    if (validPackets.length > 0) {
      const bounds = new window.google.maps.LatLngBounds();
      validPackets.forEach((p) => bounds.extend({ lat: p.lat, lng: p.lng ?? p.lon }));
      map.fitBounds(bounds, 48);
    }
  }, [isLoaded, selectedPacket, validPackets]);

  if (loadError) {
    return (
      <div className="field-map-error">
        Google Maps failed to load. Enable <strong>Maps JavaScript API</strong> and verify{" "}
        <code className="field-map-code">REACT_APP_GOOGLE_MAPS_API_KEY</code>.
      </div>
    );
  }

  if (!isLoaded) {
    return <div className="field-map-loading">Loading Google Maps…</div>;
  }

  return (
    <GoogleMap
      mapContainerClassName="responder-map-leaflet responder-map-gmaps"
      center={center}
      zoom={validPackets.length ? 14 : 12}
      onLoad={onLoad}
      onUnmount={onUnmount}
      options={{
        disableDefaultUI: false,
        zoomControl: true,
        mapTypeControl: false,
        streetViewControl: false,
        fullscreenControl: false,
        styles: FIELD_MAP_DARK_STYLES,
      }}
    >
      {validPackets.map((pkt) => {
        const lng = pkt.lng ?? pkt.lon;
        const selected = pkt.id === selectedId;
        const iconUrl = makePinIconDataUrl(pkt.urgency, selected);
        return (
          <Marker
            key={pkt.id}
            position={{ lat: pkt.lat, lng }}
            icon={{
              url: iconUrl,
              scaledSize: new window.google.maps.Size(38, 46),
              anchor: new window.google.maps.Point(19, 46),
            }}
            onClick={() => setSelectedId(pkt.id)}
            zIndex={selected ? 1000 : pkt.urgency === "RED" ? 100 : 10}
          />
        );
      })}

      {selectedPacket ? (
        <InfoWindow
          position={{
            lat: selectedPacket.lat,
            lng: selectedPacket.lng ?? selectedPacket.lon,
          }}
          onCloseClick={() => setSelectedId(null)}
          options={{ maxWidth: 320, pixelOffset: new window.google.maps.Size(0, -8) }}
        >
          <FieldMapInfoBody packet={selectedPacket} />
        </InfoWindow>
      ) : null}
    </GoogleMap>
  );
}

/**
 * Field responder map: Google Maps when REACT_APP_GOOGLE_MAPS_API_KEY or legacy REACT_APP_MAPS_API_KEY is set,
 * otherwise Leaflet + Carto dark with the same pins and selection behaviour.
 */
export default function FieldMap({ packets, selectedId, setSelectedId }) {
  const apiKey = resolveGoogleMapsApiKey();
  const useGoogle = apiKey.length >= 20;

  return (
    <div className="field-map-root">
      {useGoogle ? (
        <GoogleFieldMap packets={packets} selectedId={selectedId} setSelectedId={setSelectedId} />
      ) : (
        <LeafletFieldMap packets={packets} selectedId={selectedId} setSelectedId={setSelectedId} />
      )}
    </div>
  );
}
