const FALLBACK_CENTER = { lat: 37.7749, lng: -122.4194 };

/** CI/local parity: prefer canonical name; accept legacy `REACT_APP_MAPS_API_KEY` used in older workflows. */
function resolveGoogleMapsApiKey() {
  return (process.env.REACT_APP_GOOGLE_MAPS_API_KEY || process.env.REACT_APP_MAPS_API_KEY || "").trim();
}

