export function formatResponderPacketId(packet) {
  const base = String(packet.id);
  if (base.toLowerCase().startsWith("demo-")) {
    const letter = packet.urgency === "RED" ? "R" : packet.urgency === "YELLOW" ? "Y" : "G";
    return `#DEMO-${letter}`;
  }
  return `#${base.slice(0, 8).toUpperCase()}`;
}

export function priorityHeading(packet) {
  if (packet.urgency === "RED") return "CRITICAL (PRIORITY 1):";
  if (packet.urgency === "YELLOW") return "URGENT (PRIORITY 2):";
  return "STABLE (PRIORITY 3):";
}

export function signalsLine(packet) {
  const raw = packet.signals || "—";
  return String(raw).replace(/·/g, "-").toUpperCase();
}

export function sourceLine(packet) {
  if (packet.isAutoGenerated) return "AUTO-SOS (passive)";
  return "MANUAL / APP";
}

function escHtml(t) {
  return String(t ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/"/g, "&quot;");
}

function leafletPopupUrgencyColor(urgency) {
  if (urgency === "RED") return "#EA4335";
  if (urgency === "YELLOW") return "#FBBC04";
  return "#34A853";
}

function leafletPopupHtml(pkt) {
  const urgency = escHtml(pkt.urgency || "GREEN");
  const injury = escHtml(pkt.injury || "Unknown");
  const lat = pkt.lat ?? 0;
  const lng = pkt.lng ?? pkt.lon ?? 0;
  const confidence = Number(pkt.confidence ?? 0);
  const color = leafletPopupUrgencyColor(pkt.urgency);
  const modeLabel = pkt.isAutoGenerated ? "AUTO-SOS" : "MANUAL";

  return `<div style='font-family:monospace;min-width:200px'>
  <div style='color:${color};font-weight:700;font-size:12px;letter-spacing:1px'>${urgency}</div>
  <div style='color:#e8eaed;font-size:14px;margin:4px 0'>${injury}</div>
  <div style='color:#9aa0a6;font-size:11px'>GPS ${lat.toFixed(4)}, ${lng.toFixed(4)}</div>
  <div style='color:#9aa0a6;font-size:11px'>Conf ${(confidence * 100).toFixed(0)}% · ${modeLabel}</div>
</div>`;
}

function pinPalette(urgency) {
  if (urgency === "RED") {
    return { fill: "#EA4335", light: "#FF6659", dark: "#B31412", stroke: "#FFCDD2", letter: "R" };
  }
  if (urgency === "YELLOW") {
    return { fill: "#F9AB00", light: "#FFD567", dark: "#C08100", stroke: "#FFF8E1", letter: "Y" };
  }
  return { fill: "#34A853", light: "#81C995", dark: "#0F9D58", stroke: "#E8F5E9", letter: "G" };
}

