@Composable
private fun PacketRow(
    packet: TriagePacket,
    index: Int,
) {
    val isRed = packet.urgency == "RED"
        Row(
        modifier = Modifier
            .fillMaxWidth()
            .height(40.dp)
            .background(
                when {
                    isRed -> Color(0xFFEA4335).copy(alpha = 0.06f)
                    index % 2 == 0 -> Color(0xFF0D1117)
                    else -> Color(0xFF0A0A0A)
                }
            )
            .then(
                if (isRed) Modifier.border(
                    BorderStroke(2.dp, OmniMeshColors.MediumRed),
                    RoundedCornerShape(0.dp)
                ) else Modifier
            )
            .padding(horizontal = 12.dp, vertical = 6.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        // Spec: RED rows have a 2dp left red border. We render it as a
        // dedicated rail so it stays visible on dark alternating rows.
        Box(
            modifier = Modifier
                .width(if (isRed) 2.dp else 0.dp)
                .height(32.dp)
                .background(if (isRed) OmniMeshColors.MediumRed else Color.Transparent)
        )
        Spacer(Modifier.width(if (isRed) 8.dp else 0.dp))
        Text(
            text = (index + 1).toString(),
            color = Color(0xFF5F6368),
            fontSize = 13.sp,
            fontFamily = FontFamily.Monospace,
            modifier = Modifier.width(32.dp)
        )
        Box(modifier = Modifier.width(80.dp)) {
            UrgencyPill(packet.urgency, color = urgencyColor(packet.urgency))
        }
        Text(
            text = packet.injury.take(40).replace('_', ' '),
            color = Color(0xFFE8EAED),
            fontSize = 13.sp,
            fontFamily = GoogleSans,
            maxLines = 1,
            modifier = Modifier.weight(1f)
        )
        Text(
            text = "${(packet.confidence * 100).toInt()}%·${if (packet.isAutoGenerated) "AUTO" else "MANUAL"}",
            color = Color(0xFF9AA0A6),
            fontSize = 11.sp,
            fontFamily = FontFamily.Monospace,
            fontWeight = FontWeight.Medium,
            modifier = Modifier.width(80.dp),
            maxLines = 1
        )
    }
}

