@Composable
private fun StatCard(
    label: String,
    value: Int,
    valueColor: Color,
    glowColor: Color,
    history: List<Int>,
    modifier: Modifier = Modifier,
    border: Color? = null
) {
    val animated by animateIntAsState(
        targetValue = value,
        animationSpec = tween(800),
        label = "stat-$label"
    )
    var previousValue by remember { mutableStateOf(value) }
    val glow = remember(label) { Animatable(0f) }
    LaunchedEffect(value) {
        if (value > previousValue) {
            glow.snapTo(1f)
            glow.animateTo(0f, animationSpec = tween(800))
        }
        previousValue = value
    }
    val glowBorder = BorderStroke(
        1.dp,
        (border ?: glowColor.copy(alpha = 0.28f)).copy(alpha = 0.35f + glow.value * 0.65f)
    )
    Surface(
        modifier = modifier,
        shape = RoundedCornerShape(12.dp),
        color = OmniMeshColors.DarkSurface,
        border = glowBorder
    ) {
        Box {
            if (glow.value > 0.01f) {
                Box(
                    modifier = Modifier
                        .fillMaxSize()
                        .background(glowColor.copy(alpha = 0.10f * glow.value), RoundedCornerShape(12.dp))
                )
            }
            Column(
                modifier = Modifier.padding(horizontal = 20.dp, vertical = 18.dp),
                verticalArrangement = Arrangement.spacedBy(6.dp)
            ) {
                Text(
                    text = label,
                    color = Color(0xFF9AA0A6),
                    fontSize = 11.sp,
                    fontFamily = FontFamily.Monospace,
                    letterSpacing = 1.5.sp,
                    fontWeight = FontWeight.Medium
                )
                Text(
                    text = animated.toString(),
                    color = valueColor,
                    fontSize = 48.sp,
                    fontWeight = FontWeight.W300,
                    lineHeight = 52.sp
                )
                Sparkline(
                    values = history,
                    color = glowColor,
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(22.dp)
                )
            }
        }
    }
}

@Composable
private fun Sparkline(values: List<Int>, color: Color, modifier: Modifier = Modifier) {
    Canvas(modifier = modifier) {
        if (values.isEmpty()) return@Canvas
        val safe = if (values.size == 1) listOf(values.first(), values.first()) else values
        val min = safe.minOrNull()?.toFloat() ?: 0f
        val max = safe.maxOrNull()?.toFloat() ?: 1f
        val range = (max - min).coerceAtLeast(1f)
        val stepX = size.width / (safe.size - 1).coerceAtLeast(1)
        val path = Path()
        safe.forEachIndexed { idx, v ->
            val x = idx * stepX
            val y = size.height - ((v - min) / range) * (size.height - 3f) - 1.5f
            if (idx == 0) path.moveTo(x, y) else path.lineTo(x, y)
            drawCircle(color.copy(alpha = 0.8f), radius = 1.5f, center = Offset(x, y))
        }
        drawPath(path = path, color = color.copy(alpha = 0.8f), style = androidx.compose.ui.graphics.drawscope.Stroke(width = 1.8f))
    }
}

