@Composable
fun CommandScreen(
    viewModel: OmniMeshViewModel,
    packets: List<TriagePacket>,
    dispatchResult: DispatchAgent.DispatchRecommendation?,
    demoMode: Boolean,
    onToggleDemoMode: () -> Unit,
    onRunAgent: () -> Unit,
    onSpeakDispatch: (String) -> Unit
) {
    val scroll = rememberScrollState()
    val redCount = packets.count { it.urgency == "RED" }
    val autoCount = packets.count { it.isAutoGenerated }
    val peerCount by viewModel.peerCount.collectAsState()

    // Live clock for the header — re-emits every second on a single composable.
    var clockTick by remember { mutableStateOf(System.currentTimeMillis()) }
    LaunchedEffect(Unit) {
        while (true) {
            clockTick = System.currentTimeMillis()
            delay(1000)
        }
    }

    var analyzing by remember { mutableStateOf(false) }
    var showTimeline by remember { mutableStateOf(false) }
    val timelineEvents by viewModel.timelineEvents.collectAsState(initial = emptyList())
    val spikeAlert by viewModel.spikeAlert.collectAsState()
    val metricHistory by viewModel.commandMetricHistory.collectAsState()
    val analysisText = dispatchResult?.rawAnalysis.orEmpty()
    LaunchedEffect(dispatchResult) {
        if (dispatchResult != null) analyzing = false
    }
    LaunchedEffect(packets.size, redCount, autoCount) {
        viewModel.pushCommandMetricSnapshot(
            total = packets.size,
            critical = redCount,
            autoSos = autoCount
        )
    }

    Box(modifier = Modifier.fillMaxSize()) {
        MeshBackground(
            modifier = Modifier.fillMaxSize(),
            nodeCount = 40,
            nodeColor = Color(0xFF174EA6),
            edgeColor = Color(0xFF4285F4),
            nodeAlpha = 0.14f,
            edgeAlpha = 0.06f,
        )
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(OmniMeshColors.DarkBackground.copy(alpha = 0.88f))
        ) {
            OmniMeshTopBar(
                screenName = "COMMAND",
                peerCount = peerCount,
                showTimezone = true,
            )
            Column(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .verticalScroll(scroll)
                    .navigationBarsPadding()
                    .padding(horizontal = 16.dp)
                    .padding(top = 16.dp, bottom = 24.dp),
                verticalArrangement = Arrangement.spacedBy(16.dp)
            ) {

        CommandHeader(now = clockTick)

        StatRow(
            total = packets.size,
            critical = redCount,
            autoSos = autoCount,
            totalHistory = metricHistory["TOTAL"].orEmpty(),
            criticalHistory = metricHistory["CRITICAL"].orEmpty(),
            autoHistory = metricHistory["AUTO-SOS"].orEmpty()
