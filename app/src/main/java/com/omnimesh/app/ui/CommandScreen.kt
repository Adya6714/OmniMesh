@Composable
private fun PacketTable(packets: List<TriagePacket>) {
    val sorted = packets.sortedBy { it.urgencyPriority() }

    Surface(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(10.dp),
        color = OmniMeshColors.DarkSurface
    ) {
