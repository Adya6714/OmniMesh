@Composable
private fun TypewriterText(text: String, analyzing: Boolean, onLineCountChanged: (Int) -> Unit) {
    var displayed by remember(text) { mutableStateOf("") }
    var cursorVisible by remember { mutableStateOf(true) }
    var cursorFlash by remember { mutableStateOf(false) }

    LaunchedEffect(text) {
        displayed = ""
        onLineCountChanged(1)
        text.forEachIndexed { i, _ ->
            delay(15)
            displayed = text.substring(0, i + 1)
            onLineCountChanged(displayed.lines().size.coerceAtLeast(1))
            cursorFlash = true
            delay(30)
            cursorFlash = false
        }
    }

    LaunchedEffect(Unit) {
        while (true) {
            delay(500)
            cursorVisible = !cursorVisible
        }
    }

    val showGlyph = analyzing || displayed.length < text.length
    Text(
        text = displayed + if (showGlyph && cursorVisible) "█" else "",
        color = OmniMeshColors.MediumGreen,
        fontSize = 13.sp,
        fontFamily = FontFamily.Monospace,
        style = terminalGlowStyle(flash = cursorFlash)
    )
}

@Composable
private fun LoadingSequence(onVisibleLinesChanged: (Int) -> Unit) {
    val lines = listOf(
        "> INITIALIZING...",
        "> LOADING PACKETS...",
        "> RUNNING CLUSTER ANALYSIS..."
    )
    var visibleCount by remember { mutableStateOf(0) }
    LaunchedEffect(Unit) {
        for (i in 1..lines.size) {
            visibleCount = i
            onVisibleLinesChanged(i)
            delay(800)
        }
    }
    Column(verticalArrangement = Arrangement.spacedBy(2.dp)) {
        lines.forEachIndexed { index, line ->
            AnimatedVisibility(
                visible = visibleCount > index,
                enter = fadeIn(animationSpec = tween(260)),
                exit = fadeOut(animationSpec = tween(120))
            ) {
                Text(
                    text = line,
                    color = OmniMeshColors.MediumGreen,
                    fontSize = 12.sp,
                    fontFamily = FontFamily.Monospace,
                    style = terminalGlowStyle()
                )
            }
        }
    }
}

@Composable
private fun terminalGlowStyle(flash: Boolean = false): TextStyle = TextStyle(
    shadow = Shadow(
        color = OmniMeshColors.MediumGreen.copy(alpha = if (flash) 0.45f else 0.30f),
        offset = Offset.Zero,
        blurRadius = if (flash) 10f else 6f
    )
)

