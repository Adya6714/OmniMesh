            modifier = Modifier.fillMaxWidth()
        ) {
            // Header
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(Color(0xFF161B22))
                    .padding(horizontal = 12.dp, vertical = 8.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                TableHeaderCell("#", modifier = Modifier.width(32.dp))
                TableHeaderCell("URGENCY", modifier = Modifier.width(80.dp))
                TableHeaderCell("INJURY", modifier = Modifier.weight(1f))
                TableHeaderCell("CONF·TYPE", modifier = Modifier.width(80.dp))
            }

            sorted.forEachIndexed { index, p ->
                PacketRow(packet = p, index = index)
            }

            if (sorted.isEmpty()) {
                Text(
                    text = "(no active packets)",
                    color = OmniMeshColors.Grey,
                    fontSize = 12.sp,
                    fontFamily = FontFamily.Monospace,
                    modifier = Modifier.padding(16.dp)
                )
            }
        }
    }
}

